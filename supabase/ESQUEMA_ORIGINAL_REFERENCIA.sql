create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin' and active = true
  );
$$;

create or replace function public.claim_order_for_user(
  p_order_code text,
  p_user_id uuid,
  p_full_name text,
  p_email text
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders%rowtype;
  v_public_id text;
begin
  select * into v_order
  from public.orders
  where code = upper(trim(p_order_code))
    and status = 'available'
  for update;

  if not found then
    raise exception 'ORDER_NOT_AVAILABLE';
  end if;

  insert into public.profiles(id, full_name, email, role, active)
  values (
    p_user_id,
    coalesce(nullif(trim(p_full_name), ''), 'Usuario MELLIFERA'),
    lower(trim(p_email)),
    'user',
    true
  )
  on conflict (id) do update
    set full_name = excluded.full_name,
        email = excluded.email,
        active = true
  returning public_id into v_public_id;

  insert into public.apiaries(owner_id, name)
  select p_user_id, 'Apiario principal'
  where not exists (select 1 from public.apiaries where owner_id = p_user_id);

  insert into public.subscriptions(owner_id, plan_name, status)
  values (p_user_id, 'MELLIFERA SaaS', 'active')
  on conflict (owner_id) do nothing;

  update public.orders
  set status = 'claimed', claimed_by = p_user_id, claimed_at = now()
  where id = v_order.id;

  update public.mother_nodes
  set owner_id = p_user_id
  where order_id = v_order.id;

  return v_public_id;
end;
$$;

revoke all on function public.claim_order_for_user(text, uuid, text, text) from public;
revoke all on function public.claim_order_for_user(text, uuid, text, text) from anon;
revoke all on function public.claim_order_for_user(text, uuid, text, text) from authenticated;
grant execute on function public.claim_order_for_user(text, uuid, text, text) to service_role;

