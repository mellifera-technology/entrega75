create or replace function public.mellifera_public_id()
returns text
language sql
volatile
as $$
  select 'MEL-' || upper(substr(md5(gen_random_uuid()::text || clock_timestamp()::text || random()::text), 1, 24));
$$;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  public_id text not null unique default public.mellifera_public_id(),
  full_name text not null,
  email text not null,
  role public.app_role not null default 'user',
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  code text not null unique,
  status public.order_status not null default 'available',
  customer_note text,
  claimed_by uuid references auth.users(id) on delete set null,
  claimed_at timestamptz,
  created_at timestamptz not null default now(),
  constraint orders_code_uppercase check (code = upper(code))
